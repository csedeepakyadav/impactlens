export type AnalysisStatus =
  | 'uploaded'
  | 'analyzing'
  | 'complete'
  | 'rejected'
  | 'error';

export interface ReportRecord {
  id: string;
  fileName: string;
  fileSize: number;
  pageCount: number | null;
  instructions: string;
  typeHint: string;
  status: AnalysisStatus;
  createdAt: string;
  rejectionReason?: string;
  errorMessage?: string;
  result?: ImpactReport;
}

// SSE events emitted by GET /api/reports/:id/stream
export type StreamEvent =
  | { type: 'step'; step: JobStep; state: 'start' | 'done'; note?: string }
  | { type: 'partial'; entities?: string[]; claims?: string[] }
  | { type: 'rejected'; reason: string }
  | { type: 'error'; message: string }
  | { type: 'complete'; reportId: string };

export function bandForScore(score: number): SeverityBand {
  if (score >= 85) return 'critical';
  if (score >= 70) return 'severe';
  if (score >= 50) return 'high';
  if (score >= 30) return 'moderate';
  return 'minimal';
}

