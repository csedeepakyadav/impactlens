// ImpactReport — single source of truth for the analysis schema.
// Imported by both server (validation, prompts) and web (rendering).

export type SeverityBand = 'minimal' | 'moderate' | 'high' | 'severe' | 'critical';
export type ImpactDirection = 'negative' | 'positive' | 'mixed';

export type DocumentType =
  | 'short_seller'
  | 'investigative'
  | 'regulatory'
  | 'press_release'
  | 'news'
  | 'other';

export type DimensionKey =
  | 'market'
  | 'reputational'
  | 'legal'
  | 'financial'
  | 'operational'
  | 'sentiment';

export interface DimensionScore {
  key: DimensionKey;
  label: string;
  score: number; // 0-100
  direction: ImpactDirection;
  confidence: number; // 0-1
  rationale: string;
}

export interface EntityImpact {
  name: string;
  kind: 'company' | 'person' | 'sector' | 'other';
  score: number; // 0-100
  ticker?: string;
  summary: string;
}

export type ClaimSeverity = 'low' | 'medium' | 'high' | 'critical';

export interface Claim {
  text: string;
  severity: ClaimSeverity;
  pageRef: string; // e.g. "p. 12" or "pp. 3-5"
}

export interface HistoricalAnalog {
  event: string;
  year: number;
  outcome: string;
  similarity: number; // 0-1
}

export interface ImpactReport {
  meta: {
    id: string;
    analyzedAt: string; // ISO
    model: string;
    sourceFile: string;
  };
  document: {
    title: string;
    publisher: string;
    publishDate: string | null;
    documentType: DocumentType;
    subjectEntities: string[];
    disclosedConflicts: string[];
  };
  overall: {
    score: number; // 0-100
    band: SeverityBand;
    direction: ImpactDirection;
    summary: string;
  };
  dimensions: DimensionScore[];
  entities: EntityImpact[];
  claims: Claim[];
  timeline: {
    immediate: string;
    shortTerm: string;
    longTerm: string;
  };
  analogs: HistoricalAnalog[];
  risks: string[];
  credibility: {
    score: number; // 0-100
    rationale: string;
  };
  disclaimer: string;
}

